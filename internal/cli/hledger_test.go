func TestHledgerBackupRejectsCachePath(t *testing.T) {
	dir := t.TempDir()
	cachePath := filepath.Join(dir, "cache.sqlite")
	seedBackupCache(t, cachePath)
	want, err := os.ReadFile(cachePath)
	if err != nil {
		t.Fatal(err)
	}
	paths := []string{cachePath}
	if runtime.GOOS != "windows" {
		aliasPath := filepath.Join(dir, "cache-alias.sqlite")
		if err := os.Symlink(cachePath, aliasPath); err != nil {
			t.Fatal(err)
		}
		paths = append(paths, aliasPath)
	}

	for _, path := range paths {
		h := newCacheCommandHarness(t, cachePath, "", nil)
		if err := h.execute("--json", "hledger", "backup", path); err != nil {
			t.Fatalf("Execute() error = %v", err)
		}
		if h.ExitCode != 2 || !strings.Contains(h.Stdout.String(), "journal path must differ from cache path") {
			t.Fatalf("path=%q exitCode=%d output=%q", path, h.ExitCode, h.Stdout.String())
		}
		got, err := os.ReadFile(cachePath)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Fatalf("cache changed after rejected journal backup to %q", path)
		}
	}
}

